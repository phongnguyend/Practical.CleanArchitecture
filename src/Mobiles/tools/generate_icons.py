for name, x, y, radius in [('users', 9, 7, 4), ('users', 18, 8, 3), ('view', 12, 12, 3), ('history', 12, 12, 9), ('theme', 12, 12, 5)]:
    ICONS[name].append([(x + radius * math.cos(i * math.tau / 48), y + radius * math.sin(i * math.tau / 48)) for i in range(49)])

def distance(x, y, a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]
    t = max(0, min(1, ((x - a[0]) * dx + (y - a[1]) * dy) / (dx * dx + dy * dy)))
    return math.hypot(x - a[0] - t * dx, y - a[1] - t * dy)

def chunk(kind, data):
    return struct.pack('!I', len(data)) + kind + data + struct.pack('!I', zlib.crc32(kind + data))

for name, paths in ICONS.items():
    segments = [(a, b) for points in paths for a, b in zip(points, points[1:])]
    pixels = bytearray()
    for y in range(72):
        pixels.append(0)
        for x in range(72):
            d = min(distance((x + .5) / 3, (y + .5) / 3, a, b) for a, b in segments)
            alpha = round(max(0, min(1, (1 - d) * 3 + .5)) * 255)
            pixels.extend((0, 0, 0, alpha))
    png = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('!2I5B', 72, 72, 8, 6, 0, 0, 0)) + chunk(b'IDAT', zlib.compress(pixels)) + chunk(b'IEND', b'')
    for folder in ['Flutter/assets/icons', 'ReactNative/assets/icons', 'Kotlin/app/src/main/res/drawable-nodpi']:
        target = ROOT / folder / f'action_{name}.png'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(png)
